import { mkdirSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { createServer } from 'vite';

const root = process.cwd();
const outputPath = resolve(root, 'src/lib/typescript/data/runtime/generated.ts');

const server = await createServer({
	root,
	server: { middlewareMode: true },
	appType: 'custom',
	logLevel: 'error'
});

try {
	const module = await server.ssrLoadModule('/src/lib/typescript/data/_index_.ts');
	const data = module.data;
	const links = {};
	const children = {};

	function isRecord(value) {
		return typeof value === 'object' && value !== null && !Array.isArray(value);
	}

	function isLink(value) {
		return (
			isRecord(value) &&
			typeof value.href === 'string' &&
			typeof value.external === 'boolean' &&
			typeof value.title === 'string' &&
			typeof value.subTitle === 'string' &&
			typeof value.description === 'string' &&
			isRecord(value.img) &&
			typeof value.img.href === 'string' &&
			typeof value.img.alt === 'string'
		);
	}

	function metadata(value) {
		const result = {
			href: value.href,
			external: value.external,
			title: value.title,
			subTitle: value.subTitle,
			description: value.description,
			img: value.img
		};

		for (const key of ['label', 'seoTitle', 'sourceMetadata']) {
			if (key in value) {
				result[key] = value[key];
			}
		}

		if (isRecord(value.descriptions)) {
			result.descriptions = {};

			for (const key of ['short', 'medium']) {
				if (typeof value.descriptions[key] === 'string') {
					result.descriptions[key] = value.descriptions[key];
				}
			}
		}

		if (isRecord(value.images)) {
			result.images = value.images;
		}

		if (isRecord(value.navigation)) {
			const navigation = {};

			for (const key of ['label', 'parent', 'hidden', 'iconSize']) {
				if (key in value.navigation) {
					navigation[key] = value.navigation[key];
				}
			}

			if (Object.keys(navigation).length > 0) {
				result.navigation = navigation;
			}
		}

		return result;
	}

	function visit(value, path = '', containerPath = null) {
		if (!isRecord(value)) {
			return;
		}

		if (isLink(value) && path) {
			if (links[path]) {
				throw new Error(`Duplicate runtime metadata path: ${path}`);
			}

			links[path] = metadata(value);

			if (containerPath) {
				const navigationParent = path.endsWith('.page')
					? containerPath.split('.').slice(0, -1).join('.')
					: containerPath;

				if (navigationParent) {
					children[navigationParent] ??= [];
					children[navigationParent].push(path);
				}
			}

			return;
		}

		for (const [key, child] of Object.entries(value)) {
			if (key === 'img' || key === 'images' || key === 'logos' || key === 'tags') {
				continue;
			}

			const childPath = path ? `${path}.${key}` : key;
			visit(child, childPath, path || null);
		}
	}

	visit(data);

	function collectNavigationChildren(value, path) {
		if (!isRecord(value) || isLink(value)) {
			return [];
		}

		const result = [];

		for (const [key, child] of Object.entries(value)) {
			if (key === 'page' || key === 'img' || key === 'images' || key === 'logos' || key === 'tags') {
				continue;
			}

			const childPath = `${path}.${key}`;

			if (isLink(child)) {
				result.push(childPath);
				continue;
			}

			if (isRecord(child) && isLink(child.page)) {
				result.push(`${childPath}.page`);
				continue;
			}

			result.push(...collectNavigationChildren(child, childPath));
		}

		return result;
	}

	function collectNavigationMaps(value, path = '') {
		if (!isRecord(value) || isLink(value)) {
			return;
		}

		if (path) {
			children[path] = collectNavigationChildren(value, path);
		}

		for (const [key, child] of Object.entries(value)) {
			if (key === 'img' || key === 'images' || key === 'logos' || key === 'tags') {
				continue;
			}

			collectNavigationMaps(child, path ? `${path}.${key}` : key);
		}
	}

	collectNavigationMaps(data);

	const output = `/* Generated by scripts/generate-runtime-metadata.mjs. Do not edit. */
export type RuntimeLinkMetadata = {
	readonly href: string;
	readonly external: boolean;
	readonly title: string;
	readonly subTitle: string;
	readonly description: string;
	readonly img: { readonly href: string; readonly alt: string };
	readonly label?: string;
	readonly seoTitle?: string;
	readonly descriptions?: { readonly short?: string; readonly medium?: string };
	readonly images?: Readonly<Record<string, unknown>>;
	readonly sourceMetadata?: readonly Readonly<Record<string, unknown>>[];
	readonly navigation?: {
		readonly label?: string;
		readonly parent?: string;
		readonly hidden?: boolean;
		readonly iconSize?: 'default' | 'large';
	};
};

export const runtimeLinks: Readonly<Record<string, RuntimeLinkMetadata>> = ${JSON.stringify(links, null, 2)};
export const runtimeChildren: Readonly<Record<string, readonly string[]>> = ${JSON.stringify(children, null, 2)};
`;

	mkdirSync(resolve(root, 'src/lib/typescript/data/runtime'), { recursive: true });
	writeFileSync(outputPath, output);
} finally {
	await server.close();
}
